  function toSet(text) {
    var map = Object.create(null);
    String(text).split(/\s+/).forEach(function (word) {
      if (word) map[word] = true;
    });
    return map;
  }

  /*
   * 按顺序合并若干空格分隔的词表，保留首次出现的顺序并去重。
   * 用于「标准 SQL 基线 + 方言扩展」的组装，避免同一词条重复出现。
   */
  function mergeWords() {
    var seen = Object.create(null);
    var out = [];
    var i;
    var list;
    var words;

    for (i = 0; i < arguments.length; i++) {
      words = String(arguments[i] === null || arguments[i] === undefined ? '' : arguments[i])
        .replace(/\s+/g, ' ')
        .split(' ');
      for (list = 0; list < words.length; list++) {
        if (!words[list] || seen[words[list]]) continue;
        seen[words[list]] = true;
        out.push(words[list]);
      }
    }

    return out.join(' ');
  }

  function splitWords(text) {
    var out = [];
    var words = String(text === null || text === undefined ? '' : text).split(/\s+/);
    var i;
    for (i = 0; i < words.length; i++) {
      if (words[i]) out.push(words[i]);
    }
    return out;
  }

